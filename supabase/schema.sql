-- ========================================================
-- MYFOLIO SUPABASE POSTGRESQL SCHEMA (DDL)
-- High-Performance Portfolio Data Architecture
-- ========================================================

-- Enable UUID Extension
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- 1. CATEGORIES TABLE
CREATE TABLE IF NOT EXISTS public.categories (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name_fr VARCHAR(255) NOT NULL,
  name_en VARCHAR(255) NOT NULL,
  slug VARCHAR(255) UNIQUE NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);
ALTER TABLE public.categories ENABLE ROW LEVEL SECURITY;

-- 2. TECHNOLOGIES TABLE
CREATE TABLE IF NOT EXISTS public.technologies (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(255) NOT NULL,
  slug VARCHAR(255) UNIQUE NOT NULL,
  icon_svg TEXT,
  category VARCHAR(255) DEFAULT 'frontend',
  is_featured BOOLEAN DEFAULT TRUE,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);
ALTER TABLE public.technologies ENABLE ROW LEVEL SECURITY;

-- 3. PROJECTS TABLE
CREATE TABLE IF NOT EXISTS public.projects (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug VARCHAR(255) UNIQUE NOT NULL,
  title_fr VARCHAR(255) NOT NULL,
  title_en VARCHAR(255) NOT NULL,
  summary_fr TEXT NOT NULL,
  summary_en TEXT NOT NULL,
  problem_fr TEXT,
  problem_en TEXT,
  solution_fr TEXT,
  solution_en TEXT,
  role_fr VARCHAR(255),
  role_en VARCHAR(255),
  features_fr JSONB,
  features_en JSONB,
  featured_image VARCHAR(500),
  demo_url VARCHAR(500),
  github_url VARCHAR(500),
  category_id BIGINT REFERENCES public.categories(id) ON DELETE SET NULL,
  status VARCHAR(50) DEFAULT 'completed',
  is_featured BOOLEAN DEFAULT FALSE,
  "order" INT DEFAULT 0,
  completed_at DATE,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);
ALTER TABLE public.projects ENABLE ROW LEVEL SECURITY;

-- 4. PROJECT IMAGES TABLE
CREATE TABLE IF NOT EXISTS public.project_images (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id BIGINT REFERENCES public.projects(id) ON DELETE CASCADE,
  image_path VARCHAR(500) NOT NULL,
  caption_fr VARCHAR(255),
  caption_en VARCHAR(255),
  "order" INT DEFAULT 0,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);
ALTER TABLE public.project_images ENABLE ROW LEVEL SECURITY;

-- 5. PROJECT TECHNOLOGY PIVOT TABLE
CREATE TABLE IF NOT EXISTS public.project_technology (
  project_id BIGINT REFERENCES public.projects(id) ON DELETE CASCADE,
  technology_id BIGINT REFERENCES public.technologies(id) ON DELETE CASCADE,
  PRIMARY KEY (project_id, technology_id)
);
ALTER TABLE public.project_technology ENABLE ROW LEVEL SECURITY;

-- 6. SKILLS TABLE (TECHNICAL ECOSYSTEM)
CREATE TABLE IF NOT EXISTS public.skills (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(255) NOT NULL,
  category VARCHAR(255) NOT NULL,
  level_percentage INT DEFAULT 85,
  proficiency_label VARCHAR(100) DEFAULT 'Advanced',
  icon VARCHAR(255),
  is_featured BOOLEAN DEFAULT TRUE,
  "order" INT DEFAULT 0,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);
ALTER TABLE public.skills ENABLE ROW LEVEL SECURITY;

-- 7. EXPERIENCES TABLE
CREATE TABLE IF NOT EXISTS public.experiences (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company VARCHAR(255) NOT NULL,
  location VARCHAR(255) NOT NULL,
  position_fr VARCHAR(255) NOT NULL,
  position_en VARCHAR(255) NOT NULL,
  start_date DATE NOT NULL,
  end_date DATE,
  is_current BOOLEAN DEFAULT FALSE,
  description_fr TEXT NOT NULL,
  description_en TEXT NOT NULL,
  technologies JSONB,
  "order" INT DEFAULT 0,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);
ALTER TABLE public.experiences ENABLE ROW LEVEL SECURITY;

-- 8. EDUCATION TABLE
CREATE TABLE IF NOT EXISTS public.education (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  institution VARCHAR(255) NOT NULL,
  location VARCHAR(255) NOT NULL,
  degree_fr VARCHAR(255) NOT NULL,
  degree_en VARCHAR(255) NOT NULL,
  field_fr VARCHAR(255) NOT NULL,
  field_en VARCHAR(255) NOT NULL,
  start_date DATE NOT NULL,
  end_date DATE,
  is_current BOOLEAN DEFAULT FALSE,
  description_fr TEXT,
  description_en TEXT,
  "order" INT DEFAULT 0,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);
ALTER TABLE public.education ENABLE ROW LEVEL SECURITY;

-- 9. CERTIFICATIONS TABLE
CREATE TABLE IF NOT EXISTS public.certifications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(255) NOT NULL,
  issuer VARCHAR(255) NOT NULL,
  issue_date DATE NOT NULL,
  expiry_date DATE,
  credential_id VARCHAR(255),
  credential_url VARCHAR(500),
  badge_image VARCHAR(500),
  category VARCHAR(100) DEFAULT 'Development',
  "order" INT DEFAULT 0,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);
ALTER TABLE public.certifications ENABLE ROW LEVEL SECURITY;

-- 10. ARTICLES TABLE (BLOG & EDITORIAL)
CREATE TABLE IF NOT EXISTS public.articles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug VARCHAR(255) UNIQUE NOT NULL,
  title_fr VARCHAR(255) NOT NULL,
  title_en VARCHAR(255) NOT NULL,
  excerpt_fr TEXT NOT NULL,
  excerpt_en TEXT NOT NULL,
  content_fr TEXT NOT NULL,
  content_en TEXT NOT NULL,
  cover_image VARCHAR(500),
  reading_time INT DEFAULT 5,
  is_published BOOLEAN DEFAULT TRUE,
  published_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);
ALTER TABLE public.articles ENABLE ROW LEVEL SECURITY;

-- 11. TESTIMONIALS TABLE
CREATE TABLE IF NOT EXISTS public.testimonials (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  author_name VARCHAR(255) NOT NULL,
  author_role_fr VARCHAR(255) NOT NULL,
  author_role_en VARCHAR(255) NOT NULL,
  author_company VARCHAR(255) NOT NULL,
  author_avatar VARCHAR(500),
  content_fr TEXT NOT NULL,
  content_en TEXT NOT NULL,
  project_slug VARCHAR(255),
  "order" INT DEFAULT 0,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);
ALTER TABLE public.testimonials ENABLE ROW LEVEL SECURITY;

-- 12. CONTACT MESSAGES TABLE
CREATE TABLE IF NOT EXISTS public.contact_messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sender_name VARCHAR(255) NOT NULL,
  sender_email VARCHAR(255) NOT NULL,
  subject VARCHAR(255) NOT NULL,
  message TEXT NOT NULL,
  project_type VARCHAR(100),
  budget_range VARCHAR(100),
  is_read BOOLEAN DEFAULT FALSE,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);
ALTER TABLE public.contact_messages ENABLE ROW LEVEL SECURITY;

-- ROW LEVEL SECURITY (RLS) POLICIES
DROP POLICY IF EXISTS "Public Read Categories" ON public.categories;
DROP POLICY IF EXISTS "Public Read Technologies" ON public.technologies;
DROP POLICY IF EXISTS "Public Read Projects" ON public.projects;
DROP POLICY IF EXISTS "Public Read Skills" ON public.skills;
DROP POLICY IF EXISTS "Public Read Experiences" ON public.experiences;
DROP POLICY IF EXISTS "Public Read Certifications" ON public.certifications;
DROP POLICY IF EXISTS "Public Read Articles" ON public.articles;
DROP POLICY IF EXISTS "Public Read Testimonials" ON public.testimonials;
DROP POLICY IF EXISTS "Public Insert Contact Messages" ON public.contact_messages;
DROP POLICY IF EXISTS "Admin Full Access Skills" ON public.skills;
DROP POLICY IF EXISTS "Admin Full Access Projects" ON public.projects;

-- Allow Public Read Access for Portfolio Data
CREATE POLICY "Public Read Categories" ON public.categories FOR SELECT USING (true);
CREATE POLICY "Public Read Technologies" ON public.technologies FOR SELECT USING (true);
CREATE POLICY "Public Read Projects" ON public.projects FOR SELECT USING (true);
CREATE POLICY "Public Read Skills" ON public.skills FOR SELECT USING (true);
CREATE POLICY "Public Read Experiences" ON public.experiences FOR SELECT USING (true);
CREATE POLICY "Public Read Certifications" ON public.certifications FOR SELECT USING (true);
CREATE POLICY "Public Read Articles" ON public.articles FOR SELECT USING (true);
CREATE POLICY "Public Read Testimonials" ON public.testimonials FOR SELECT USING (true);

-- Allow Public Insert for Contact Form Submissions
CREATE POLICY "Public Insert Contact Messages" ON public.contact_messages FOR INSERT WITH CHECK (true);

-- Allow Authenticated / Service Role Full Access
CREATE POLICY "Admin Full Access Skills" ON public.skills FOR ALL USING (true);
CREATE POLICY "Admin Full Access Projects" ON public.projects FOR ALL USING (true);
